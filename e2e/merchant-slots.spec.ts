import { test, expect } from '@playwright/test'
test.use({ baseURL: process.env.SLOTS_BASE_URL ?? 'http://127.0.0.1:5174' })
const token = `test.${Buffer.from(JSON.stringify({ role: 'ROLE_MERCHANT', exp: Math.floor(Date.now() / 1000) + 3600 })).toString('base64url')}.test`
for (const width of [1440, 390]) {
  test(`lot capacity data and editing at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.addInitScript((value) => localStorage.setItem('access_token', value), token)
    await page.route('**/api/v1/merchant/profile', (route) => route.fulfill({ json: { data: { merchantId: 101, fullName: 'Chủ bãi' } } }))
    await page.route('**/api/v1/merchant/parking-lots/35', (route) => route.fulfill({ json: { data: { id: 35, name: 'Bến Cảng Quận 1', address: 'Quận 1, TP. Hồ Chí Minh', status: 'APPROVED' } } }))
    const slots = [{ id: 1, vehicleType: 'CONTAINER', totalCapacity: 20, availableCapacity: 8 }, { id: 2, vehicleType: 'LIGHT_TRUCK', totalCapacity: 10, availableCapacity: 4 }]
    await page.route('**/api/v1/parking-lots/35/slots', (route) => route.fulfill({ json: { data: slots } }))
    await page.route('**/api/v1/merchant/parking-lots/35/slots/bulk', async (route) => {
      const payload = route.request().postDataJSON()
      expect(payload.slots).toHaveLength(2)
      await route.fulfill({ json: { data: slots.map((slot, i) => ({ ...slot, totalCapacity: payload.slots[i].totalCapacity, availableCapacity: slot.availableCapacity + payload.slots[i].totalCapacity - slot.totalCapacity })) } })
    })
    await page.goto('/merchant/parking-lots/35/slots')
    await expect(page.getByText('Bến Cảng Quận 1', { exact: true })).toBeVisible()
    await expect(page.getByRole('spinbutton')).toHaveCount(2)
    await expect(page.getByTestId('kpi-total-cap')).toHaveText('30')
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `docs/09-audit/scr-032-capacity-${width}.png`, fullPage: true })
    await page.getByRole('button', { name: 'Tăng sức chứa Xe container' }).click()
    await expect(page.getByTestId('kpi-total-cap')).toHaveText('31')
    await page.getByRole('button', { name: 'Lưu sức chứa' }).click()
    await expect(page.getByRole('status')).toContainText('Lưu cấu hình sức chứa thành công')
    await expect(page.getByRole('button', { name: 'Lưu sức chứa' })).toBeDisabled()
    await page.getByRole('button', { name: 'Giảm sức chứa Xe container' }).click()
    await page.getByRole('button', { name: 'Lưu sức chứa' }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    expect(errors).toEqual([])
  })
}

test('empty lot: add types, set capacity, save and reload', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript((value) => localStorage.setItem('access_token', value), token)
  await page.route('**/api/v1/merchant/profile', (route) => route.fulfill({ json: { data: { merchantId: 101, fullName: 'Chủ bãi' } } }))
  await page.route('**/api/v1/merchant/parking-lots/35', (route) => route.fulfill({ json: { data: { id: 35, name: 'Bến Cảng Quận 1', address: 'Quận 1, TP. Hồ Chí Minh', status: 'APPROVED' } } }))
  let saved: { id: number; vehicleType: string; totalCapacity: number; availableCapacity: number }[] = []
  await page.route('**/api/v1/parking-lots/35/slots', (route) => route.fulfill({ json: { data: saved } }))
  await page.route('**/api/v1/merchant/parking-lots/35/slots/bulk', async (route) => {
    const payload: { slots: { vehicleType: string; totalCapacity: number }[] } = route.request().postDataJSON()
    expect(payload.slots).toEqual([{ vehicleType: 'HEAVY_TRUCK', totalCapacity: 25 }, { vehicleType: 'CONTAINER', totalCapacity: 10 }])
    saved = payload.slots.map((slot, index) => ({ ...slot, id: index + 1, availableCapacity: slot.totalCapacity }))
    await route.fulfill({ json: { data: saved } })
  })
  await page.goto('/merchant/parking-lots/35/slots')
  await expect(page.getByText('Chưa có cấu hình sức chứa')).toBeVisible()
  await page.getByLabel('Loại xe cần thêm').selectOption('HEAVY_TRUCK')
  await page.getByRole('button', { name: 'Thêm loại xe' }).click()
  await page.getByLabel('Sức chứa', { exact: true }).fill('25')
  await page.getByLabel('Loại xe cần thêm').selectOption('CONTAINER')
  await page.getByRole('button', { name: 'Thêm loại xe' }).click()
  await page.getByLabel('Sức chứa', { exact: true }).nth(1).fill('10')
  await expect(page.getByTestId('kpi-total-cap')).toHaveText('35')
  await page.getByLabel('Loại xe cần thêm').selectOption('SEDAN_SUV')
  await page.getByRole('button', { name: 'Thêm loại xe' }).click()
  await page.getByLabel('Sức chứa', { exact: true }).nth(2).fill('5')
  await expect(page.getByTestId('kpi-total-cap')).toHaveText('40')
  await page.getByRole('button', { name: 'Bỏ loại xe Ô tô con / SUV' }).click()
  await expect(page.getByTestId('kpi-total-cap')).toHaveText('35')
  await expect(page.getByRole('spinbutton')).toHaveCount(2)
  await expect(page.getByLabel('Loại xe cần thêm')).toBeFocused()
  await page.getByRole('button', { name: 'Lưu sức chứa' }).click()
  await expect(page.getByRole('status')).toContainText('Lưu cấu hình sức chứa thành công')
  await page.reload()
  await expect(page.getByRole('spinbutton')).toHaveCount(2)
  await expect(page.getByTestId('kpi-total-cap')).toHaveText('35')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'docs/09-audit/scr-032-add-types-390.png', fullPage: true })
})
