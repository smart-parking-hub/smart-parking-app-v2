import fs from 'node:fs'
import {chromium,expect} from '@playwright/test'
const account=JSON.parse(fs.readFileSync('../smart-parking-service-microservice/.env.real-data-session.json','utf8')).a
const browser=await chromium.launch({channel:'msedge',headless:true})
try{
 const context=await browser.newContext({viewport:{width:1440,height:1100},locale:'vi-VN'})
 const page=await context.newPage()
 await page.goto('http://localhost:3000/login?next=%2Fvehicles')
 await page.locator('#login-phone').fill(account.phone)
 await page.locator('#login-password').fill(account.password)
 await page.getByRole('button',{name:'Đăng nhập',exact:true}).click()
 await page.waitForURL('**/vehicles')
 await page.getByRole('button',{name:'Thêm phương tiện',exact:true}).click()
 const plate=page.getByLabel('Biển số xe',{exact:true})
 await plate.fill('51c - 123.45')
 await page.getByLabel('Nhãn hiệu / Model (không bắt buộc)',{exact:true}).fill('Hyundai')
 await expect(plate).toHaveValue('51C-123.45')
 await expect(page.getByLabel('Loại xe',{exact:true})).toHaveValue('')
 await expect(page.getByRole('option',{name:'Hyundai',exact:true})).toBeVisible()
 await expect(page.getByText('Thông tin tự khai',{exact:true})).toBeVisible()
 await page.getByRole('heading',{name:'Thêm phương tiện',exact:true}).scrollIntoViewIfNeeded()
 await page.screenshot({path:'../docs/fe-be-integration/vehicle-form-guided-desktop.png'})
 await page.getByRole('button',{name:'Hủy',exact:true}).click()
 await expect(page.getByRole('table')).toBeVisible()
 await page.getByRole('heading',{name:/Phương tiện đã đăng ký/}).scrollIntoViewIfNeeded()
 await page.screenshot({path:'../docs/fe-be-integration/vehicle-table-desktop.png'})
 await page.getByRole('button',{name:'Thêm phương tiện',exact:true}).click()
 const brand=page.getByLabel('Nhãn hiệu / Model (không bắt buộc)',{exact:true})
 await brand.fill('B')
 await expect(page.getByRole('option',{name:'Mitsubishi',exact:true})).toBeVisible()
 await page.screenshot({path:'../docs/fe-be-integration/vehicle-brand-suggestions.png'})
 await brand.press('ArrowDown');await brand.press('Enter')
 await expect(brand).toHaveValue('Mitsubishi')
 await expect(page.getByRole('listbox')).toHaveCount(0)
 await page.getByRole('button',{name:'Hủy',exact:true}).click()
 await page.setViewportSize({width:390,height:844})
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2))throw new Error('Mobile page overflow')
 await page.screenshot({path:'../docs/fe-be-integration/vehicle-table-mobile.png',fullPage:true})
 const report={passed:true,checks:['Plate uppercase and whitespace normalization','Custom white brand suggestions support ArrowDown/Enter and free text without autofilling other fields','Self-declared information clearly labeled','Navy table header and contained horizontal table scrolling on 390px mobile'],apiWrites:0}
 fs.writeFileSync('../docs/fe-be-integration/vehicle-form-guided-results.json',JSON.stringify(report,null,2))
 console.log(JSON.stringify(report))
} finally {await browser.close()}
